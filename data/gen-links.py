#!/usr/bin/env python3
"""Generate per-track link appendices from the Colosseum corpus.

Every URL in context/tracks/*.md comes from data/colosseum-resources.json
verbatim. Never hand-type a link into those files -- re-run this instead:

    ./data/refresh.sh
"""
import json, os, sys, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CORPUS = os.path.join(ROOT, "data", "colosseum-resources.json")
OUT = os.path.join(ROOT, "context", "tracks", "_links")

# Boilerplate that is identical on every track; emitted once, not per track.
SKIP_SECTIONS = {"Company formation and banking"}


def clean(s):
    return re.sub(r"\s+", " ", (s or "").strip())


def render(track):
    out = []
    for section in track.get("resources", []):
        sname = clean(section.get("hyperlink") or section.get("title") or section.get("name"))
        if sname in SKIP_SECTIONS:
            continue
        out.append(f"### {sname}\n")
        for group in section.get("groups", []):
            gname = clean(group.get("hyperlink") or group.get("title") or group.get("name"))
            if gname and gname != sname:
                out.append(f"**{gname}**\n")
            for link in group.get("links", []):
                label = clean(link.get("hyperlink") or link.get("label"))
                url = link.get("url")
                desc = clean(link.get("description"))
                out.append(f"- [{label}]({url})")
                if desc:
                    out.append(f"  - {desc}")
            out.append("")
    return "\n".join(out).rstrip() + "\n"


def main():
    d = json.load(open(CORPUS))
    os.makedirs(OUT, exist_ok=True)
    tracks = {t["id"]: t for t in d["tracks"]}
    for tid, t in tracks.items():
        body = (
            f"<!-- GENERATED by data/gen-links.py from data/colosseum-resources.json. Do not edit by hand. -->\n"
            f"# {t['name']} — Colosseum resource index\n\n"
            f"Every link below is copied verbatim from Colosseum's published corpus, "
            f"including its curator caveats.\n\n"
            + render(t)
        )
        path = os.path.join(OUT, f"{tid}.md")
        with open(path, "w") as f:
            f.write(body)
        n = body.count("\n- [")
        print(f"  {tid:12s} {n:3d} links -> context/tracks/_links/{tid}.md")


if __name__ == "__main__":
    main()
