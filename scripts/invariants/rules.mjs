/**
 * The checked-in rule table that keeps the architecture spine honest in CI, with no network (plan Appendix C.1.2).
 * Shapes follow Masayume 68f7a09:scripts/invariants/rules.mjs:
 *  - pattern rules: { scopes, exts, exclude?, pattern } — every non-comment line matching `pattern` is a finding
 *  - file rules:    { file, mustMatch?, mustNotMatch?, optional? } — a single file's content is asserted
 *  - check rules:   { check(rule, ctx) } — arbitrary logic returning findings
 */
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { execSync } from "node:child_process";
import { finding } from "./lib/report.mjs";
import { codeLines, readText, walkFiles } from "./lib/walk.mjs";

const TS = [".ts", ".tsx"];
const JS = [".mjs", ".js"];
const OUTSIDE_MARKETS = ["web", "mobile", "packages/core", "packages/db", "packages/brain", "packages/clients", "services", "scripts"];
const MAX_FILE_LINES = 400;
const SEND_FILES = ["packages/markets/src/tx/send.ts"];
const ABI_DIR = "packages/clients/src/abis";

function fileLength(rule, ctx) {
  const findings = [];
  for (const scope of rule.scopes) {
    for (const { rel, abs } of walkFiles(ctx.root, scope, rule.exts, rule.exclude ?? [])) {
      const lines = readText(abs).split("\n").length;
      if (lines > MAX_FILE_LINES) findings.push(finding(rule, `${lines} lines (max ${MAX_FILE_LINES})`, rel));
    }
  }
  return findings;
}

/** Sends happen only in the submitter's send module (plan C.1.2 write-boundary). */
function writeBoundary(rule, ctx) {
  const findings = [];
  const pattern = /\b(writeContract|sendTransaction|sendTransactionSync|sendRawTransaction|sendCalls|sendCallsSync)\s*\(/;
  for (const scope of [...OUTSIDE_MARKETS, "packages/markets"]) {
    for (const { rel, abs } of walkFiles(ctx.root, scope, TS, ["scripts/invariants"])) {
      if (SEND_FILES.includes(rel) || rel.endsWith(".test.ts")) continue;
      for (const [lineNo, line] of codeLines(readText(abs))) {
        const match = pattern.exec(line);
        if (match) findings.push(finding(rule, `\`${match[0]}\``, `${rel}:${lineNo}`));
      }
    }
  }
  return findings;
}

/** Generated ABIs carry the codegen header; nobody hand-writes contract ABIs. */
function generatedAbi(rule, ctx) {
  const dir = join(ctx.root, ABI_DIR);
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => !readFileSync(join(dir, f), "utf8").startsWith("// Generated by scripts/codegen/clients.mjs"))
    .map((f) => finding(rule, "missing the codegen header", `${ABI_DIR}/${f}`));
}

function parseAbi(text) {
  return JSON.parse(text.slice(text.indexOf("["), text.lastIndexOf("]") + 1).replace(/,\s*\]$/, "]"));
}

/** Payouts go to msg.sender: no withdraw/claim/redeem function takes a destination address (P6). */
function noDestinationAbi(rule, ctx) {
  const dir = join(ctx.root, ABI_DIR);
  if (!existsSync(dir)) return [];
  const allowed = new Set(["send", "creditFor", "sendDeferred", "resendOwed", "quoteSend"]);
  const findings = [];
  for (const file of readdirSync(dir)) {
    for (const entry of parseAbi(readFileSync(join(dir, file), "utf8"))) {
      if (entry.type !== "function" || allowed.has(entry.name)) continue;
      if (/^(withdraw|claim|redeem|cashOut|payout)/i.test(entry.name) && entry.inputs.some((i) => i.type === "address" && /^(to|recipient|receiver|dest|destination)/i.test(i.name))) {
        findings.push(finding(rule, `${entry.name} takes a destination (${entry.inputs.map((i) => i.name).join(", ")})`, `${ABI_DIR}/${file}`));
      }
    }
  }
  return findings;
}

/** Hand-pinned Tempo predeploys agree with viem's `Addresses` (plan C.1.2 address-drift). */
async function addressDrift(rule, ctx) {
  const pinned = await import(pathToFileURL(join(ctx.root, "packages/clients/src/pinned.ts")).href);
  const require = createRequire(join(ctx.root, "packages/markets/package.json"));
  const viemTempo = await import(pathToFileURL(require.resolve("viem/tempo")).href);
  const live = viemTempo.Addresses ?? {};
  const pairs = { pathUSD: "pathUsd", feeManager: "feeManager", accountKeychain: "accountKeychain", addressRegistry: "addressRegistry", nonce: "nonceManager", stablecoinDex: "stablecoinDex", tip20Factory: "tip20Factory", tip403Registry: "tip403Registry", receivePolicyGuard: "receivePolicyGuard", signatureVerifier: "signatureVerifier", storageCredits: "storageCredits" };
  const findings = [];
  for (const [ours, theirs] of Object.entries(pairs)) {
    const actual = live[theirs];
    if (typeof actual !== "string") continue;
    if (actual.toLowerCase() !== pinned.TEMPO[ours].toLowerCase()) findings.push(finding(rule, `${ours}: pinned ${pinned.TEMPO[ours]}, viem/tempo ships ${actual}`));
  }
  return findings;
}

/** Every deployed area has a relay policy file; the vault policy keeps capital intake unsponsored (D-020 / D-029). */
function relayPolicyCoverage(rule, ctx) {
  const deployments = join(ctx.root, "contracts/deployments");
  if (!existsSync(deployments)) return [];
  const findings = [];
  const areas = new Set();
  for (const chain of readdirSync(deployments).filter((d) => /^\d+$/.test(d))) {
    for (const f of readdirSync(join(deployments, chain)).filter((f) => f.endsWith(".json") && !f.endsWith(".pending.json"))) areas.add(f.replace(/\.json$/, ""));
  }
  // `v4` is the Uniswap v4 replay the launchpad's graduation calls directly. D-231 moved `stocks`, `guard`, `pools` and
  // `themes` to contracts/deployments/retired/ (no app write reads them), so only `v4` is exempt.
  const exempt = new Set(["v4"]);
  for (const area of areas) {
    if (exempt.has(area)) continue;
    const policy = join(ctx.root, `packages/markets/src/relay/policies/${area}.ts`);
    if (!existsSync(policy)) findings.push(finding(rule, `area "${area}" is deployed but has no relay policy`, `packages/markets/src/relay/policies/${area}.ts`));
  }
  const vault = join(ctx.root, "packages/markets/src/relay/policies/vault.ts");
  if (existsSync(vault)) {
    const text = readFileSync(vault, "utf8");
    for (const name of ["deposit", "depositAndGrant", "grant", "fundGrant"]) {
      if (!new RegExp(`never[\\s\\S]*"${name}"`).test(text)) findings.push(finding(rule, `vault policy must list "${name}" as never sponsored`, "packages/markets/src/relay/policies/vault.ts"));
    }
  }
  return findings;
}

/** `/dev/*` answers 404 in production (C.3.6). */
function devRoutesGated(rule, ctx) {
  const dir = join(ctx.root, "web/src/app/dev");
  if (!existsSync(dir)) return [];
  const layout = join(dir, "layout.tsx");
  if (!existsSync(layout)) return [finding(rule, "web/src/app/dev has no layout.tsx gate", "web/src/app/dev")];
  return /notFound\(\)/.test(readFileSync(layout, "utf8")) ? [] : [finding(rule, "dev layout does not call notFound()", "web/src/app/dev/layout.tsx")];
}

/** No agent/tool instruction files anywhere in the tracked tree (owner rule). */
function noAgentFiles(rule, ctx) {
  const tracked = execSync("git ls-files", { cwd: ctx.root }).toString().split("\n");
  return tracked.filter((p) => /(^|\/)(CLAUDE|AGENTS)\.md$/i.test(p) && !p.startsWith("reference/")).map((p) => finding(rule, "agent instruction file is tracked", p));
}

