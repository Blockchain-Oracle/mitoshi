/**
 * Writes `packages/core/src/stocks/liquidity.vectors.json`: the TS ports of TickMath / SqrtPriceMath / LiquidityAmounts
 * (`packages/core/src/stocks/liquidity.ts`) evaluated on house-plan-shaped inputs, checked against the Solidity
 * libraries by `contracts/test/tempo/stocks/LiquidityTwin.t.sol`.
 *   pnpm --dir scripts exec tsx fixtures/liquidity-vectors.ts
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { sqrtFromTokenPrice } from "../../packages/core/src/stocks/guard";
import { getAmount0Delta, getAmount1Delta, getLiquidityForAmounts, getSqrtPriceAtTick, getTickAtSqrtPrice } from "../../packages/core/src/stocks/liquidity";
import { planHouse } from "../../packages/core/src/stocks/housePlan";

const ticks = [-887_272, -887_220, -200_000, -59_940, -58_860, -57_480, -1, 0, 1, 60, 12_345, 200_000, 887_220, 887_272];
const tick = ticks.map((t) => ({ tick: t, sqrt: getSqrtPriceAtTick(t).toString() }));
const prices = [357_406_776_030_000_000_000n, 246_304_483_230_000_000_000n, 187_481_926_700_000_000_000n, 607_993_110_420_000_000_000n, 10n ** 18n, 10n ** 14n];
const atSqrt = prices.map((p) => {
  const s = sqrtFromTokenPrice(p);
  return { sqrt: s.toString(), tick: getTickAtSqrtPrice(s) };
});
const liquidity = prices.flatMap((p) => {
  const s = sqrtFromTokenPrice(p);
  return planHouse({ sqrtPriceX96: s, tokenPriceE18: p, mirror: 30_000_000n, ladderUsd: 20_000_000_000n }).map((x) => {
    const sa = getSqrtPriceAtTick(x.tickLower);
    const sb = getSqrtPriceAtTick(x.tickUpper);
    return {
      label: x.label, sqrt: s.toString(), tickLower: x.tickLower, tickUpper: x.tickUpper,
      amount0: "1234567890123", amount1: "30000000",
      liquidity: getLiquidityForAmounts(s, sa, sb, 1_234_567_890_123n, 30_000_000n).toString(),
      planLiquidity: x.liquidity.toString(),
      d0up: getAmount0Delta(sa, sb, x.liquidity, true).toString(), d0down: getAmount0Delta(sa, sb, x.liquidity, false).toString(),
      d1up: getAmount1Delta(sa, sb, x.liquidity, true).toString(), d1down: getAmount1Delta(sa, sb, x.liquidity, false).toString(),
    };
  });
});
const out = { comment: "Generated by scripts/fixtures/liquidity-vectors.ts; checked by LiquidityTwin.t.sol", tick, atSqrt, liquidity };
const path = join(import.meta.dirname, "..", "..", "packages", "core", "src", "stocks", "liquidity.vectors.json");
writeFileSync(path, `${JSON.stringify(out, null, 2)}\n`);
console.log(`wrote ${path}: ${tick.length} ticks, ${atSqrt.length} prices, ${liquidity.length} positions`);
