/**
 * Writes `packages/core/src/stocks/guard.vectors.json`, the vectors shared by the TS twin (`guard.test.ts`) and the
 * Solidity library (`contracts/test/tempo/stocks/GuardMath.t.sol`). Prices come from real sources where one exists:
 * TSLA 356.83185257 (RedStone TSLA---24_7, 2026-09-29, fixtures/prints), SPY mid 763.025 with its live multiplier
 * 1.00171799 (research 14 §3.3), CRWD's 4-for-1 multiplier 4e18 (RH mainnet, effectiveAt 1782999000).
 *
 *   pnpm --dir scripts exec tsx fixtures/guard-vectors.ts
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { allowed, band, sqrtFromTokenPrice, tokenPriceE18, tokenPriceFromSqrt } from "../../packages/core/src/stocks/guard";

const e18 = (s: string): bigint => {
  const [i, f = ""] = s.split(".");
  return BigInt(i!) * 10n ** 18n + BigInt((f + "0".repeat(18)).slice(0, 18));
};

const shares: [string, bigint, bigint][] = [
  ["TSLA", e18("356.83185257"), e18("1")],
  ["SPY", e18("763.025"), e18("1.00171799")],
  ["CRWD", e18("120.5125"), e18("4")],
  ["CRWD-pre-split", e18("482.05"), e18("1")],
  ["PLTR", e18("177.6281"), e18("1")],
  ["AMD", e18("559.6543"), e18("1")],
  ["AMZN", e18("253.5998"), e18("1")],
  ["penny", e18("0.0001"), e18("1")],
  ["whale", e18("1000000"), e18("1")],
  ["frac-mult", e18("10"), 1_021_500_000_000_000_000n],
];

const tokenPrice = shares.map(([name, share, mult]) => ({ name, share: share.toString(), mult: mult.toString(), price: tokenPriceE18(share, mult).toString() }));
const prices = tokenPrice.map((t) => BigInt(t.price));
const sqrt = prices.map((p) => ({ price: p.toString(), sqrt: sqrtFromTokenPrice(p).toString() }));
const fromSqrt = sqrt.map((s) => ({ sqrt: s.sqrt, price: tokenPriceFromSqrt(BigInt(s.sqrt)).toString() }));
const bands = prices.flatMap((p) => [150, 300, 500, 2000].map((bps) => {
  const { lo, hi } = band(p, bps);
  return { price: p.toString(), bps, lo: lo.toString(), hi: hi.toString() };
}));

// allowed(): every region of pre × post around one real band (TSLA regular 150 bps).
const { lo, hi } = band(prices[0]!, 150);
const mid = (lo + hi) / 2n;
const below = lo - (hi - lo);
const above = hi + (hi - lo);
const cases: [string, bigint, bigint, boolean][] = [
  ["in → in", mid, mid + 1n, true],
  ["in → lo edge", mid, lo, true],
  ["in → hi edge", mid, hi, true],
  ["in → below", mid, lo - 1n, false],
  ["in → above", mid, hi + 1n, false],
  ["below → closer, still below", below, below + 10n, true],
  ["below → into band", below, mid, true],
  ["below → overshoot above", below, hi + 1n, false],
  ["below → further below", below, below - 1n, false],
  ["below → unchanged", below, below, false],
  ["above → closer, still above", above, above - 10n, true],
  ["above → into band", above, mid, true],
  ["above → overshoot below", above, lo - 1n, false],
  ["above → further above", above, above + 1n, false],
  ["above → unchanged", above, above, false],
];
const allowedV = cases.map(([name, pre, post, ok]) => {
  if (allowed(pre, post, lo, hi) !== ok) throw new Error(`allowed() disagrees with the table: ${name}`);
  return { name, pre: pre.toString(), post: post.toString(), lo: lo.toString(), hi: hi.toString(), ok };
});

const out = { comment: "Generated by scripts/fixtures/guard-vectors.ts; checked by guard.test.ts and GuardMath.t.sol", tokenPrice, sqrt, fromSqrt, band: bands, allowed: allowedV };
const path = join(import.meta.dirname, "..", "..", "packages", "core", "src", "stocks", "guard.vectors.json");
writeFileSync(path, `${JSON.stringify(out, null, 2)}\n`);
console.log(`wrote ${path}: ${tokenPrice.length} prices, ${bands.length} bands, ${allowedV.length} allowed cases`);
