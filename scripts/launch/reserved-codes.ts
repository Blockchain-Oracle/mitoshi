/**
 * Builds the reserved currency codes (plan B.5.1 `isReservedCode`: ISO-4217 + the Robinhood Stock Token tickers + "USD")
 * from their real sources, and writes both twins:
 *   - `packages/core/src/launch/reserved-codes.json` (read by `currencyGuard.ts`)
 *   - `contracts/src/launch/ReservedCodes.sol` (a sorted packed table `LaunchRegistry.isReservedCode` searches)
 * `test/tempo/launch/LaunchRegistry.t.sol` checks the Solidity table against the JSON, so they cannot drift.
 *
 *   tsx scripts/launch/reserved-codes.ts
 *
 * Sources: ISO 4217 List One, the maintenance agency's (SIX) published XML; Robinhood Chain mainnet Stock Tokens
 * (docs.robinhood.com/chain/contracts, 195 tokens, context/tempo/14-bridging-stock-tokens.md Appendix A).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..", "..");
const ISO_URL = "https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-one.xml";

const xml = await (await fetch(ISO_URL)).text();
const published = /Pblshd="([^"]+)"/.exec(xml)?.[1];
if (!published) throw new Error("ISO list: no Pblshd attribute");
const iso = [...new Set([...xml.matchAll(/<Ccy>([A-Z]{3})<\/Ccy>/g)].map((m) => m[1]!))].sort();
if (iso.length < 150 || !iso.includes("USD") || !iso.includes("EUR")) throw new Error(`ISO list looks wrong (${iso.length} codes)`);

const appendix = readFileSync(join(ROOT, "context", "tempo", "14-bridging-stock-tokens.md"), "utf8").split("## Appendix A")[1] ?? "";
const tickers = [...appendix.matchAll(/^\| (\d+) \| ([A-Z0-9.]+) \|/gm)].map((m) => m[2]!);
if (tickers.length !== 195) throw new Error(`expected 195 Stock Token tickers, found ${tickers.length}`);

const all = [...new Set([...iso, ...tickers, "USD"])].sort();
for (const c of all) if (!/^[A-Z0-9]{1,8}$/.test(c)) throw new Error(`code ${c} does not fit the 8-byte table`);

const json = {
  note: "Generated by scripts/launch/reserved-codes.ts — do not edit.",
  sources: {
    iso4217: `ISO 4217 List One (SIX), published ${published}: ${ISO_URL}`,
    stockTokens: "Robinhood Chain mainnet Stock Tokens (docs.robinhood.com/chain/contracts, read 2026-09-21; context/tempo/14 Appendix A)",
  },
  iso4217: iso,
  stockTokens: tickers,
  all,
};
writeFileSync(join(ROOT, "packages", "core", "src", "launch", "reserved-codes.json"), `${JSON.stringify(json, null, 2)}\n`);

// Solidity: `all` as big-endian uppercase ASCII, left-aligned in 8 bytes, sorted (byte order = string order).
const hex = all.map((c) => Buffer.from(c.padEnd(8, "\0"), "latin1").toString("hex")).join("");
const lines = hex.match(/.{1,96}/g)!.map((l) => `        hex"${l}"`).join("\n");
const sol = `// SPDX-License-Identifier: MIT
// Generated by scripts/launch/reserved-codes.ts from packages/core/src/launch/reserved-codes.json — do not edit.
pragma solidity 0.8.30;

/// @notice Reserved currency codes (plan B.5.1): ISO 4217 List One (published ${published}) + the ${tickers.length} Robinhood
///         Stock Token tickers + "USD", ${all.length} codes. Each is uppercase ASCII, left-aligned in 8 bytes, sorted.
library ReservedCodes {
    uint256 internal constant COUNT = ${all.length};

    bytes internal constant TABLE =
${lines};

    /// @return true when \`code\` (already uppercased, ≤ 8 bytes) is in the table
    function contains(bytes8 code) internal pure returns (bool) {
        bytes memory table = TABLE;
        uint256 lo;
        uint256 hi = COUNT;
        while (lo < hi) {
            uint256 mid = (lo + hi) >> 1;
            bytes8 at;
            assembly {
                at := mload(add(add(table, 32), mul(mid, 8)))
            }
            if (at == code) return true;
            if (at < code) lo = mid + 1;
            else hi = mid;
        }
        return false;
    }
}
`;
writeFileSync(join(ROOT, "contracts", "src", "launch", "ReservedCodes.sol"), sol);
console.log(`reserved codes: ${iso.length} ISO (published ${published}) + ${tickers.length} tickers → ${all.length} unique`);
