/**
 * Builds `fair.vectors.json`: the on-chain fair-value model (`fair.ts` ≡ `FairValue.sol`) beside Agari's float model
 * (`agari.ts`, `seat/fair.ts`) on the same inputs. `scripts/fair/fair-vectors.ts` writes the file; `fair.test.ts` proves
 * the file is what this builder produces and bounds the distance to Agari; `contracts/test/fair/FairValue.t.sol`
 * replays every row on the library bit for bit. Columnar (one array per field) so forge reads each with one cheatcode;
 * every value is below 2^53.
 */
import { fairProbUp, fairYesTicks, TRADING_YEAR_SEC } from "./agari";
import { fairProbUpE6, fairYesTicksE6, fairZE4, sigmaE8FromBps } from "./fair";

export interface FairVectors {
  note: string;
  /** Measured over the rows: the largest |upE6 − agariUpE6| and |yesTicks − agariTicks|. */
  maxUpE6Diff: number;
  maxTicksDiff: number;
  spotE8: number[];
  openE8: number[];
  tauSec: number[];
  sigmaBps: number[];
  sigmaE8: number[];
  minTick: number[];
  zE4: number[];
  upE6: number[];
  yesTicks: number[];
  agariUpE6: number[];
  agariTicks: number[];
}

const E8 = 100_000_000n;
/** BTC, ETH, SOL and a stock (Agari's worked open of 400), in e8. */
const OPENS = [90_000n * E8, 2_500n * E8, 150n * E8, 400n * E8];
const MOVES_BPS = [-300, -100, -30, -10, -3, -1, 0, 1, 3, 10, 30, 100, 300];
const TAUS = [0, 5, 60, 150, 300, 3_600];
const SIGMAS_BPS = [4_500, 5_000, 8_000];

export function buildFairVectors(): FairVectors {
  const v: FairVectors = {
    note: "Generated by scripts/fair/fair-vectors.ts from packages/core/src/fair/fairVectors.ts — do not edit.",
    maxUpE6Diff: 0, maxTicksDiff: 0,
    spotE8: [], openE8: [], tauSec: [], sigmaBps: [], sigmaE8: [], minTick: [], zE4: [], upE6: [], yesTicks: [], agariUpE6: [], agariTicks: [],
  };
  const row = (spotE8: bigint, openE8: bigint, tauSec: number, sigmaBps: number, minTick: number) => {
    const sigmaE8 = sigmaE8FromBps(sigmaBps, TRADING_YEAR_SEC);
    const up = fairProbUpE6(spotE8, openE8, sigmaE8, tauSec);
    const agariUp = Math.round(fairProbUp({ spotE8, openE8, secondsLeft: tauSec, sigmaBps }) * 1e6);
    const ticks = fairYesTicksE6(up, minTick);
    const agariTicks = fairYesTicks({ spotE8, openE8, secondsLeft: tauSec, sigmaBps, minTick });
    v.spotE8.push(Number(spotE8));
    v.openE8.push(Number(openE8));
    v.tauSec.push(tauSec);
    v.sigmaBps.push(sigmaBps);
    v.sigmaE8.push(Number(sigmaE8));
    v.minTick.push(minTick);
    v.zE4.push(Number(fairZE4(spotE8, openE8, sigmaE8, tauSec)));
    v.upE6.push(Number(up));
    v.yesTicks.push(ticks);
    v.agariUpE6.push(agariUp);
    v.agariTicks.push(agariTicks);
    v.maxUpE6Diff = Math.max(v.maxUpE6Diff, Math.abs(Number(up) - agariUp));
    v.maxTicksDiff = Math.max(v.maxTicksDiff, Math.abs(ticks - agariTicks));
  };
  // Agari's own worked cases (`quote.test.ts`): open 400, 150 s left, σ 4,500 bp, minTick 20.
  for (const spot of [400n, 401n, 399n, 440n, 360n]) row(spot * E8, 400n * E8, 150, 4_500, 20);
  row(401n * E8, 400n * E8, 30, 4_500, 20);
  row(401n * E8, 400n * E8, 3_000, 4_500, 20);
  // The grid: four opens × thirteen moves × six clocks × three σ.
  for (const open of OPENS)
    for (const bps of MOVES_BPS)
      for (const tau of TAUS)
        for (const sigma of SIGMAS_BPS) row(open + (open * BigInt(bps)) / 10_000n, open, tau, sigma, 1);
  // Extremes: a spot a thousandth / a thousand times the open saturate at the clamp.
  row(40_000_000n, 400n * E8, 300, 4_500, 1);
  row(400_000n * E8, 400n * E8, 300, 4_500, 1);
  return v;
}
